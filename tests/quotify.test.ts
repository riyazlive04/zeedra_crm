import { describe, expect, it } from "vitest";
import {
  calcCentralSubsidy,
  calcStateSubsidy,
  calcTNEBBimonthlyBill,
  computeQuotify,
  EMPTY_CUSTOM,
  fmtINR,
  quotationConfig,
  resolvePrices,
  reverseCalcTNEBBimonthlyUnits,
  type QuotifyInput,
} from "@/lib/solar/quotify";
import { DEFAULT_SETTINGS } from "@/lib/settings";

const P = resolvePrices({}, EMPTY_CUSTOM);
const opts = { stateSubsidy: true, companyName: "Acme Solar" };
const base: QuotifyInput = { sizeMode: "direct", directKw: 1.65, structure: "lowrise", dcCableSize: "4", acCableSize: "4", systemType: "dcr", panelType: "bifacial", panelWatt: 550, inverterPhase: "single" };

describe("quotation engine", () => {
  // Reference: a 1.65 kW On-Grid DCR quotation generated by the production quotation app.
  it("reproduces the reference quotation to the rupee", () => {
    const r = computeQuotify(base, P, EMPTY_CUSTOM, opts);
    expect(r.panels).toBe(3);
    expect(r.actualKw).toBe(1.65);
    expect(r.inverterLabel).toBe("3kW");
    expect(r.rows).toHaveLength(14);
    expect(fmtINR(r.preTax)).toBe("₹1,02,328");
    expect(fmtINR(r.gst)).toBe("₹9,107");
    expect(r.blendPct).toBe(8.9);
    expect(fmtINR(r.grandTotal)).toBe("₹1,11,435");
    expect([r.centralSubsidy, r.stateSubsidy]).toEqual([49500, 5000]);
    expect(fmtINR(r.netCost)).toBe("₹56,935");
    expect(fmtINR(r.savings.bimonthlySave)).toBe("₹1,295");
    expect(fmtINR(r.savings.annualSave)).toBe("₹7,772");
    expect(r.savings.paybackYrs.toFixed(1)).toBe("7.3");
    expect(fmtINR(r.savings.netBenefit30)).toBe("₹5,57,499");
    expect(r.rows.at(-1)).toMatchObject({ content: "Installation", make: "Acme Solar", qty: 1.65 });
  });

  it("sizes from bi-monthly units: units/2/30 ÷ (peak sun × efficiency)", () => {
    const r = computeQuotify({ ...base, sizeMode: "eb", bimonthlyUnits: 600 }, P, EMPTY_CUSTOM, opts);
    // 300 units/month → 10/day → 10 / 3.6 = 2.78 kW → 5.05 panels → 5 × 550 W
    expect(r.panels).toBe(5);
    expect(r.actualKw).toBe(2.75);
  });

  it("backs GST out of an adjusted final price", () => {
    const r = computeQuotify({ ...base, overrideTotal: 100000 }, P, EMPTY_CUSTOM, opts);
    expect(r.overridden).toBe(true);
    expect(r.grandTotal).toBe(100000);
    expect(r.preTax).toBe(Math.round(100000 / 1.089));
    expect(r.preTax + r.gst).toBe(100000);
    expect(r.netCost).toBe(100000 - 54500);
  });

  it("gives subsidy on DCR only, with the state top-up switchable", () => {
    expect(computeQuotify({ ...base, systemType: "ndcr", panelType: "topcon", panelWatt: 600 }, P, EMPTY_CUSTOM, opts).subsidy).toBe(0);
    expect(computeQuotify(base, P, EMPTY_CUSTOM, { ...opts, stateSubsidy: false }).subsidy).toBe(49500);
    expect(calcCentralSubsidy(2.5)).toBe(69000);
    expect(calcCentralSubsidy(4)).toBe(78000);
    expect([0.9, 1, 2.2, 2.75, 3].map((kw) => calcStateSubsidy(kw, true))).toEqual([0, 5000, 10000, 10000, 22000]);
  });

  it("adds floors to the earth cable on high-rise buildings", () => {
    const r = computeQuotify({ ...base, structure: "highrise", floors: 3 }, P, EMPTY_CUSTOM, opts);
    expect(r.rows.find((x) => x.content === "Earth Cable")).toMatchObject({ qty: 54, desc: "54m" });
    expect(r.rows.find((x) => x.content === "Module Mounting Structure")?.desc).toBe("Elevated GI HDP");
  });

  it("builds the hybrid BoQ with battery and hybrid inverter", () => {
    const r = computeQuotify({ ...base, systemType: "hybrid", directKw: 5 }, P, EMPTY_CUSTOM, opts);
    expect(r.rows.map((x) => x.content)).toContain("Battery (Lithium)");
    expect(r.rows.find((x) => x.content === "Hybrid Inverter")?.desc).toBe("5kW 1Ph");
  });

  it("round-trips the TNEB bill table", () => {
    expect(calcTNEBBimonthlyBill(456.4)).toBeCloseTo(1295.32, 2);
    expect(reverseCalcTNEBBimonthlyUnits(calcTNEBBimonthlyBill(900))).toBeCloseTo(900, 6);
    expect(reverseCalcTNEBBimonthlyUnits(1800)).toBe(500);
  });

  it("starts from the default price sheet in settings", () => {
    expect(quotationConfig(DEFAULT_SETTINGS).P.margin).toBe(10);
    expect(DEFAULT_SETTINGS.quotation.paymentStages.reduce((s, x) => s + x.pct, 0)).toBe(100);
  });
});
